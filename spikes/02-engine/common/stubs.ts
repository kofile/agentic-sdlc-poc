// Engine-neutral stubs + ledger. No model calls: schema-shaped JSON after a short delay.
import { appendFileSync, mkdirSync, readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const dataDir = () => process.env.DATA_DIR ?? join(HERE, '..', 'data', 'default');
const ensure = () => mkdirSync(join(dataDir(), 'out'), { recursive: true });
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

export type Policy = { team: string; gates: Record<string, 'human' | 'auto'>; humanTimeoutSec: number };
export type Knobs = { executeMs?: number; afterEffectMs?: number; failDesignFirstN?: number; designMs?: number };

export function loadPolicyFile(team: string): Policy {
  return JSON.parse(readFileSync(join(HERE, '..', 'teams', `${team}.json`), 'utf8'));
}

/** Every stub invocation (incl. retries/replays) is logged here: lets tests count re-executions. */
export function logCall(runId: string, step: string, extra: object = {}) {
  ensure();
  appendFileSync(join(dataDir(), 'calls.jsonl'), JSON.stringify({ t: Date.now(), pid: process.pid, runId, step, ...extra }) + '\n');
}
export function readJsonl(file: string): any[] {
  const p = join(dataDir(), file);
  return existsSync(p) ? readFileSync(p, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [];
}
export const countCalls = (runId: string, step: string) => readJsonl('calls.jsonl').filter((c) => c.runId === runId && c.step === step).length;

/** Real side effects append here. `once` = idempotency guard (skip if (runId,step) already present). */
export function ledgerAppend(runId: string, step: string, detail: object = {}, once = false) {
  ensure();
  if (once && readJsonl('ledger.jsonl').some((l) => l.runId === runId && l.step === step)) return false;
  appendFileSync(join(dataDir(), 'ledger.jsonl'), JSON.stringify({ t: Date.now(), pid: process.pid, runId, step, ...detail }) + '\n');
  return true;
}

export async function triageStub(runId: string, ticket: { id: string; grade?: string }) {
  logCall(runId, 'triage'); await sleep(200);
  const grade = ticket.grade ?? 'A';
  return { grade, issues: grade > 'B' ? ['acceptance criteria missing'] : [], storyPoints: 3 };
}
export async function routeStub(runId: string, ticket: { id: string }) {
  logCall(runId, 'route'); await sleep(200);
  return { repos: [{ name: 'kofile/example-service', role: 'primary', confidence: 0.9 }] };
}
export async function designStub(runId: string, ticket: { id: string }, feedback: string | null, round: number, knobs: Knobs = {}) {
  const prior = countCalls(runId, 'design');
  logCall(runId, 'design', { round, feedback });
  await sleep(knobs.designMs ?? 300);
  if (prior < (knobs.failDesignFirstN ?? 0)) throw new Error(`stub model 529 overloaded (call #${prior + 1})`);
  return { title: `Design for ${ticket.id}`, rev: round, addressedFeedback: feedback, body: `design v${round}${feedback ? ` (addresses: ${feedback})` : ''}` };
}
export async function planStub(runId: string, design: object) {
  logCall(runId, 'plan'); await sleep(200);
  return { tasks: [{ id: 't1', title: 'implement' }, { id: 't2', title: 'test' }] };
}
export async function executeStub(runId: string, knobs: Knobs = {}, guard = false) {
  logCall(runId, 'execute:start');
  await sleep(knobs.executeMs ?? 2000); // "agent working"
  ensure();
  writeFileSync(join(dataDir(), 'out', `${runId}.txt`), `generated by pid ${process.pid}\n`);
  const wrote = ledgerAppend(runId, 'execute:write-file', { file: `out/${runId}.txt` }, guard);
  logCall(runId, 'execute:effect-done');
  await sleep(knobs.afterEffectMs ?? 0); // window between effect and being acked to the engine
  return { files: [`out/${runId}.txt`], wrote };
}
export async function openPrStub(runId: string, guard = false) {
  logCall(runId, 'open-pr');
  ledgerAppend(runId, 'open-pr', { pr: `https://example.invalid/pr/${runId}` }, guard);
  return { url: `https://example.invalid/pr/${runId}` };
}
export const mergeStub = async (runId: string, guard = false) => { logCall(runId, 'merge'); ledgerAppend(runId, 'merge', {}, guard); return { merged: true }; };
